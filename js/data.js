// 가장 가까운 동네 (한국 밖이면 null)
function nearestPlace(lat, lon) {
  let best = null, bestD = Infinity;
  const k = Math.cos(lat * Math.PI / 180);
  for (const [name, plat, plon] of KR_PLACES) {
    const dy = (lat - plat) * 111, dx = (lon - plon) * 111 * k;
    const d = Math.sqrt(dx * dx + dy * dy);
    if (d < bestD) { bestD = d; best = name; }
  }
  return bestD <= 60 ? { name: best, km: Math.round(bestD) } : null;
}
